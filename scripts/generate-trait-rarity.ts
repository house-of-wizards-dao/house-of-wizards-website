/**
 * Generate trait occurrence counts for wizards, warriors, and souls.
 *
 * Run with: pnpm generate:trait-rarity
 */

import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";
import prettier from "prettier";
import {
  soulDisplayParts,
  warriorDisplayParts,
  wizardDisplayParts,
} from "../src/data/character-display-parts";
import { soulTraits } from "../src/data/soulTraits";
import { soulsWithTraitsMap } from "../src/data/soulsWithTraitsMap";
import { warriorTraits } from "../src/data/warriorTraits";
import { warriorsWithTraitsMap } from "../src/data/warriorsWithTraitsMap";
import { wizardTraits } from "../src/data/wizardTraits";
import { wizardsWithTraitsMap } from "../src/data/wizardsWithTraitsMap";
import { buildTraitRarity, groupTraitCounts } from "../src/lib/trait-rarity";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outputPath = path.join(__dirname, "../src/data/traitRarity.ts");

const traitRarity = {
  wizards: groupTraitCounts(
    buildTraitRarity(Object.values(wizardsWithTraitsMap), wizardDisplayParts),
    wizardTraits,
  ),
  warriors: groupTraitCounts(
    buildTraitRarity(Object.values(warriorsWithTraitsMap), warriorDisplayParts),
    warriorTraits,
  ),
  souls: groupTraitCounts(
    buildTraitRarity(Object.values(soulsWithTraitsMap), soulDisplayParts),
    soulTraits,
  ),
};

const output = `// Generated by scripts/generate-trait-rarity.ts. Do not edit by hand.
import type { TraitRarityCollection } from "@/lib/trait-rarity";

export const traitRarity: {
  wizards: TraitRarityCollection;
  warriors: TraitRarityCollection;
  souls: TraitRarityCollection;
} = ${JSON.stringify(traitRarity, null, 2)};
`;

const formatted = await prettier.format(output, { filepath: outputPath });
fs.writeFileSync(outputPath, formatted);
console.log(`Wrote ${outputPath}`);
